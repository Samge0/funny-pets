// CHART[attacker][defender] = multiplier；未列出的组合 = 1
const CHART = T.map(() => T.map(() => 1));
function set(attacker, defenders, mult) {
  for (const d of defenders) CHART[T.indexOf(attacker)][T.indexOf(d)] = mult;
}

