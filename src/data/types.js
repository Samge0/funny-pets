export function effectiveness(attackerType, defenderType) {
  return CHART[T.indexOf(attackerType)][T.indexOf(defenderType)];
}

// 防守方受到的综合倍率（双属性时相乘）
export function effectivenessAgainst(atkType, defTypes) {
  return defTypes.reduce((m, dt) => m * effectiveness(atkType, dt), 1);
}

